import { describe, expect, it } from 'vitest';
import { testApp } from '../review/testApp.mjs';
import { cli, selftest } from './selftest.mjs';

describe('selftest', () => {
  it('prints the source files and what each glob lists, without judging', () => {
    const root = testApp({
      'src/a.ts': '',
      'src/gql/g.ts': '',
      'src/a.test.ts': '',
      '.github/ci.json': JSON.stringify({
        unmeasured: {
          files: ['src/gql/**: generated by graphql-codegen', 'old/**: removed', 'bare'],
        },
      }),
    });
    expect(selftest(root)).toEqual([
      'unmeasured: 2 source files, 1 listed globs.',
      '  src/gql/**: generated by graphql-codegen (1 source files)',
      '  malformed: "old/**: removed" gives too short a reason: say in a few words why it isn\'t measured.',
      '  malformed: "bare" has no "<glob>: <reason>" shape: write the glob, ": ", then why it isn\'t measured.',
    ]);
  });
});

describe('selftest, on a glob that matches nothing', () => {
  it('warns, still without judging', () => {
    const root = testApp({
      'src/a.ts': '',
      '.github/ci.json': JSON.stringify({
        unmeasured: { files: ['old/**: removed long ago now'] },
      }),
    });
    expect(selftest(root)).toEqual([
      'unmeasured: 1 source files, 1 listed globs.',
      '  old/**: removed long ago now (0 source files)',
      'warn  old/** matches no tracked file',
    ]);
    expect(cli([root], () => {})).toBe(0);
  });
});

describe('cli', () => {
  it("passes on an app it can read, and fails one whose setting it can't", () => {
    /** @type {string[]} */
    const out = [];
    expect(cli([testApp({})], (l) => out.push(l))).toBe(0);
    expect(out).toEqual(['unmeasured: 0 source files, 0 listed globs.']);
    const bad = testApp({ '.github/ci.json': '{"unmeasured": {"files": 1}}' });
    expect(cli([bad], (l) => out.push(l))).toBe(1);
    expect(out.at(-1)).toContain('unmeasured self-test failed');
  });
});
