import { mkdtempSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { testApp, writeFiles } from '../review/testApp.mjs';
import {
  REPORT,
  classify,
  failures,
  isSource,
  main,
  measuredFiles,
  readEntries,
  readReport,
  realPath,
  trackedFiles,
} from './check.mjs';

describe('isSource', () => {
  it('counts code, wherever it is', () => {
    for (const file of [
      'src/a.ts',
      'src/b.tsx',
      'api/c.js',
      'x.jsx',
      'scripts/d.mjs',
      'e.cjs',
      'f.mts',
      'g.cts',
      'codegen.ts',
    ]) {
      expect(isSource(file), file).toBe(true);
    }
  });
  it('skips what is never app code, by name and folder', () => {
    for (const file of [
      'src/a.test.ts',
      'e2e/home.spec.ts',
      '.github/scripts/eval-should-grade.test.mjs',
      'src/__tests__/helpers/api.ts',
      'src/__mocks__/x.js',
      'src/vite-env.d.ts',
      'types/a.d.mts',
      'vite.config.ts',
      'eslint.config.js',
      '.dependency-cruiser.cjs',
      'README.md',
      'src/a.css',
    ]) {
      expect(isSource(file), file).toBe(false);
    }
  });
  it('treats a config name below the root, or a dotfile in a folder, as source', () => {
    expect(isSource('src/app.config.ts')).toBe(true);
    expect(isSource('.github/scripts/grade.mjs')).toBe(true);
  });
});

describe('measuredFiles', () => {
  it('makes absolute keys relative, and drops those outside the root', () => {
    const root = '/r/app';
    const report = {
      '/r/app/src/a.ts': {},
      'src/b.ts': {},
      '/elsewhere/c.ts': {},
      '/r/app': {},
      '../d.ts': {},
    };
    expect([...measuredFiles(report, root)].sort()).toEqual(['src/a.ts', 'src/b.ts']);
  });
  it('is empty for an empty report', () => {
    expect(measuredFiles({}, '/r').size).toBe(0);
  });
});

describe('readEntries', () => {
  it('splits entries into globs, and keeps the malformed apart', () => {
    const { entries, malformed } = readEntries({
      files: ['src/gql/**: generated by graphql-codegen', 'no reason given', 'a.ts: gen'],
    });
    expect(entries).toEqual([
      { glob: 'src/gql/**', text: 'src/gql/**: generated by graphql-codegen' },
    ]);
    expect(malformed).toHaveLength(2);
    expect(malformed[0]).toContain('no "<glob>: <reason>" shape');
    expect(malformed[1]).toContain('too short a reason');
  });
  it('takes no key as nothing listed', () => {
    expect(readEntries({})).toEqual({ entries: [], malformed: [] });
  });
  it('refuses an unknown setting or a list that is not strings', () => {
    expect(() => readEntries({ file: [] })).toThrow('no setting file');
    expect(() => readEntries({ files: 'a: b c d' })).toThrow('must be a list');
    expect(() => readEntries({ files: [1] })).toThrow('must be a list');
  });
});

describe('classify', () => {
  const tracked = [
    'src/a.ts',
    'src/b.ts',
    'src/gql/g.ts',
    'src/a.test.ts',
    'vite.config.ts',
    'README.md',
  ];
  it('sorts each source file into measured, listed or unmeasured', () => {
    const result = classify(tracked, new Set(['src/a.ts']), [
      { glob: 'src/gql/**', text: 'src/gql/**: generated code here' },
    ]);
    expect(result).toEqual({
      measured: ['src/a.ts'],
      listed: ['src/gql/g.ts'],
      unmeasured: ['src/b.ts'],
      stale: [],
    });
  });
  it('finds an entry that lists nothing unmeasured, measured or gone', () => {
    const measured = { glob: 'src/a.ts', text: 'src/a.ts: measured after all' };
    const gone = { glob: 'old/**', text: 'old/**: removed long ago' };
    expect(classify(tracked, new Set(['src/a.ts']), [measured, gone]).stale).toEqual([
      measured,
      gone,
    ]);
  });
  it("doesn't enter a dot folder with a wildcard: such a path is named outright", () => {
    const files = ['.github/scripts/x.mjs'];
    expect(classify(files, new Set(), [{ glob: '**/*.mjs', text: '' }]).unmeasured).toEqual(files);
    expect(
      classify(files, new Set(), [{ glob: '.github/scripts/*.mjs', text: '' }]).listed,
    ).toEqual(files);
  });
});

describe('failures', () => {
  it('says how to fix each', () => {
    const out = failures(
      {
        measured: [],
        listed: [],
        unmeasured: ['src/b.ts'],
        stale: [{ glob: 'old/**', text: 'old/**: removed long ago' }],
      },
      ['"x" has no shape'],
    );
    expect(out[0]).toMatch(
      /^src\/b\.ts isn't measured.*widen the coverage include.*istanbul ignore file/,
    );
    expect(out[1]).toContain('"old/**: removed long ago" matches no unmeasured file');
    expect(out[1]).toContain('Delete the entry');
    expect(out[2]).toBe('.github/ci.json unmeasured.files "x" has no shape');
  });
});

describe('realPath', () => {
  it('resolves a link, and leaves a path that is not there as it is', () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'real-'));
    symlinkSync(dir, `${dir}-link`);
    expect(realPath(`${dir}-link`)).toBe(realPath(dir));
    expect(realPath('/no/such/file.ts')).toBe('/no/such/file.ts');
  });
});

describe('readReport', () => {
  it('says how to get a report when there is none, or it is not one', () => {
    const root = testApp({});
    expect(() => readReport(root)).toThrow(/missing.*"json" reporter/);
    writeFiles(root, { [REPORT]: '{"a": ' });
    expect(() => readReport(root)).toThrow(
      /coverage-final\.json isn't valid JSON .*re-run the coverage run/,
    );
    writeFiles(root, { [REPORT]: '[]' });
    expect(() => readReport(root)).toThrow("isn't a coverage report");
    writeFiles(root, { [REPORT]: '{"a": {}}' });
    expect(readReport(root)).toEqual({ a: {} });
  });
});

describe('trackedFiles', () => {
  it('says to run from the checkout when git fails', () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'not-git-'));
    expect(() => trackedFiles(path.join(dir, 'missing'))).toThrow(
      /git ls-files failed .*run this step from the app's checkout/,
    );
  });

  it('lists what git tracks, odd names included', () => {
    const root = testApp({ 'src/a b.ts': '', 'src/"q".ts': '' });
    writeFiles(root, { 'untracked.ts': '' });
    expect(trackedFiles(root).sort()).toEqual(['package.json', 'src/"q".ts', 'src/a b.ts']);
  });
});

describe('main', () => {
  /**
   * @param {Record<string, string>} files
   * @param {string[]} measured
   */
  function app(files, measured) {
    const root = testApp(files);
    const report = Object.fromEntries(measured.map((f) => [path.join(root, f), {}]));
    writeFiles(root, { [REPORT]: JSON.stringify(report) });
    return root;
  }
  /**
   * @param {string} root
   * @param {boolean} [actions]
   */
  function run(root, actions = false) {
    /** @type {string[]} */
    const out = [];
    return { code: main(root, { log: (l) => out.push(l), actions }), out };
  }

  it('passes when every source file is measured or listed', () => {
    const root = app(
      {
        'src/a.ts': '',
        'src/gql/g.ts': '',
        '.github/ci.json': JSON.stringify({
          unmeasured: { files: ['src/gql/**: generated by graphql-codegen'] },
        }),
      },
      ['src/a.ts'],
    );
    expect(run(root)).toEqual({
      code: 0,
      out: ['unmeasured: every source file is measured (1) or listed with a reason (1).'],
    });
  });

  it('fails an unmeasured file, as an annotation on Actions', () => {
    const root = app({ 'src/a.ts': '', 'src/b.ts': '' }, ['src/a.ts']);
    const { code, out } = run(root, true);
    expect(code).toBe(1);
    expect(out[0]).toMatch(/^::error::src\/b\.ts isn't measured/);
    expect(out.at(-1)).toBe('unmeasured: 1 to fix (unmeasured/check.mjs says what counts).');
  });

  it('matches a report of real paths against a root given through a link', () => {
    const root = app({ 'src/a.ts': '' }, []);
    writeFiles(root, { [REPORT]: JSON.stringify({ [path.join(realPath(root), 'src/a.ts')]: {} }) });
    const link = `${root}-link`;
    symlinkSync(root, link);
    expect(run(link).code).toBe(0);
  });

  it('fails a missing report or a bad setting, saying why', () => {
    const root = testApp({ 'src/a.ts': '' });
    expect(run(root).out[0]).toContain('coverage/coverage-final.json is missing');
    const bad = app({ '.github/ci.json': '{"unmeasured": {"files": "x"}}' }, []);
    const { code, out } = run(bad);
    expect(code).toBe(1);
    expect(out[0]).toContain('must be a list');
  });
});
