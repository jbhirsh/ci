import { describe, expect, it } from 'vitest';
import { RETRY_WAIT_MS, crashed, failedBody, main, markerFor, releasedBody } from './crash.mjs';

const SHA = '0123456789abcdef0123456789abcdef01234567';
const NEW = 'fedcba9876543210fedcba9876543210fedcba98';
const URL = 'https://github.com/jbhirsh/app/actions/runs/1';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n';

const ran = JSON.stringify([
  { type: 'system', subtype: 'init' },
  { type: 'assistant', message: {} },
  { type: 'result', subtype: 'error_max_turns', is_error: true, result: '' },
]);

describe('crashed', () => {
  it('counts no file, an unreadable one, and one with no turn as a crash', () => {
    expect(crashed(null)).toBe(true);
    expect(crashed('')).toBe(true);
    expect(crashed('{not json')).toBe(true);
    expect(crashed('{"type":"assistant"}')).toBe(true);
    expect(crashed(JSON.stringify([{ type: 'system' }, null]))).toBe(true);
  });
  it('counts an API error before any turn as a crash: the model was never reached', () => {
    const text = JSON.stringify([
      { type: 'system', subtype: 'init' },
      { type: 'result', is_error: true, result: 'API Error: 529 overloaded' },
    ]);
    expect(crashed(text)).toBe(true);
  });
  it('counts a run with a turn as having run, however it ended', () => {
    expect(crashed(ran)).toBe(false);
    const died = JSON.stringify([{ type: 'assistant' }, { type: 'user' }]);
    expect(crashed(died)).toBe(false);
    const apiError = JSON.stringify([
      { type: 'assistant' },
      { type: 'result', is_error: true, result: 'API Error: 500' },
    ]);
    expect(crashed(apiError)).toBe(false);
  });
});

describe('releasedBody', () => {
  it('rewrites the CI marker so no count matches it, keeping one footer', () => {
    const body = `${markerFor('ci', SHA)}\nAutofix is looking at the failed checks on 0123456: ci. Attempt 1 of 2.${FOOTER}`;
    const out = releasedBody(body, 'ci', SHA, URL);
    expect(out).not.toMatch(/<!-- autofix-ci:[0-9a-f]* -->/);
    expect(out).toContain(`<!-- autofix-ci-crashed:${SHA} -->`);
    expect(out).toContain(URL);
    expect(out.split('Generated by').length).toBe(2);
  });
  it('drops both of the review fixer’s markers, whatever the line ending', () => {
    const body = `<!-- autofix-review-round -->\r\n${markerFor('review', SHA)}\nAutofix is addressing 2 review thread(s). Round 1 of 2.${FOOTER}`;
    const out = releasedBody(body, 'review', SHA, URL);
    expect(out).not.toContain('autofix-review-round');
    expect(out).not.toMatch(/autofix-review-head:/);
    expect(out).toContain(`<!-- autofix-review-crashed:${SHA} -->`);
  });
});

describe('failedBody', () => {
  it('names the fixer, the head and the run', () => {
    expect(failedBody('ci', SHA, URL)).toContain('the failed checks on 0123456');
    expect(failedBody('review', SHA, URL)).toContain('the review threads');
    expect(failedBody('ci', SHA, URL)).toContain(URL);
  });
});

/**
 * @param {{ head?: string, file?: string | null, comments?: { id: number, user: string, body: string }[] }} [over]
 */
function fakeIo(over = {}) {
  /** @type {Record<string, string>} */
  const outputs = {};
  /** @type {string[]} */
  const calls = [];
  /** @type {import('./crash.mjs').Io} */
  const io = {
    head: () => over.head ?? SHA,
    read: (file) => {
      calls.push(`read ${file}`);
      return over.file === undefined ? null : over.file;
    },
    remove: (file) => calls.push(`remove ${file}`),
    reset: (sha) => calls.push(`reset ${sha}`),
    comments: () => over.comments ?? [],
    edit: (_repo, id, body) => calls.push(`edit ${id} ${body}`),
    post: (_repo, pr, body) => calls.push(`post ${pr} ${body}`),
    output: (name, value) => {
      outputs[name] = value;
    },
    wait: (ms) => calls.push(`wait ${ms}`),
  };
  return { io, outputs, calls };
}

const ENV = {
  GITHUB_REPOSITORY: 'jbhirsh/app',
  PR: '7',
  HEAD_SHA: SHA,
  EXECUTION_FILE: '/tmp/x.json',
  RUN_URL: URL,
};

describe('main retry', () => {
  it('retries a crash from the head as it was', () => {
    const { io, outputs, calls } = fakeIo();
    expect(main(['retry'], ENV, io)).toEqual({
      log: expect.stringMatching(/once more/),
      fail: false,
    });
    expect(outputs).toEqual({ retry: 'true', report: 'false' });
    expect(calls).toEqual([
      'read /tmp/x.json',
      `wait ${RETRY_WAIT_MS}`,
      `reset ${SHA}`,
      'remove /tmp/x.json',
    ]);
  });
  it('reports, and does not retry, a run that failed', () => {
    const { io, outputs, calls } = fakeIo({ file: ran });
    main(['retry'], ENV, io);
    expect(outputs).toEqual({ retry: 'false', report: 'true' });
    expect(calls).not.toContainEqual(expect.stringMatching(/^reset/));
  });
  it('leaves a fixer that pushed to the runs on its new head', () => {
    const { io, outputs, calls } = fakeIo({ head: NEW });
    expect(main(['retry'], ENV, io).log).toContain(NEW);
    expect(outputs).toEqual({ retry: 'false', report: 'false' });
    expect(calls).toEqual([]);
  });
  it('falls back to the action’s default file in RUNNER_TEMP', () => {
    const { io, calls } = fakeIo();
    main(['retry'], { ...ENV, EXECUTION_FILE: '', RUNNER_TEMP: '/rt' }, io);
    expect(calls[0]).toBe('read /rt/claude-execution-output.json');
  });
});

describe('main report', () => {
  it('comments on a run that failed', () => {
    const { io, calls } = fakeIo({ file: ran });
    expect(main(['report', 'ci'], ENV, io).fail).toBe(true);
    expect(calls.at(-1)).toMatch(/^post 7 Autofix's attempt at the failed checks/);
  });
  it('releases the bot’s own marker after a second crash, never a look-alike', () => {
    const body = `${markerFor('ci', SHA)}\nAttempt 1 of 2.${FOOTER}`;
    const { io, calls } = fakeIo({
      comments: [
        { id: 1, user: 'someone', body },
        { id: 2, user: 'github-actions[bot]', body },
      ],
    });
    expect(main(['report', 'ci'], ENV, io).fail).toBe(true);
    expect(calls.at(-1)).toMatch(/^edit 2 <!-- autofix-ci-crashed:/);
  });
  it('fails when its marker comment is gone', () => {
    const { io } = fakeIo({ comments: [{ id: 1, user: 'someone', body: markerFor('ci', SHA) }] });
    expect(() => main(['report', 'ci'], ENV, io)).toThrow('no marker comment');
  });
  it('does nothing, and fails nothing, for a fixer that pushed', () => {
    const { io, calls } = fakeIo({ head: NEW });
    expect(main(['report', 'review'], ENV, io).fail).toBe(false);
    expect(calls).toEqual([]);
  });
});

describe('main usage', () => {
  it('fails an unknown mode or fixer, or a missing variable', () => {
    const { io } = fakeIo();
    expect(() => main(['nope'], ENV, io)).toThrow('usage');
    expect(() => main(['report', 'x'], ENV, io)).toThrow('usage');
    expect(() => main(['retry'], { ...ENV, PR: '' }, io)).toThrow('PR is not set');
  });
});
