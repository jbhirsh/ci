// What Claude autofix does when a fixer's Claude step fails. Each fixer's
// marker comment goes up before Claude starts, so that two completions
// close together can't both fix; but then a fixer that dies before doing
// anything has spent its head's one attempt, and nothing else completes on
// that head to wake another run (BoardGames #298: a 504 while the step set
// up, then exit 127, and the PR sat red under "Attempt 1 of 2").
//
// So a failure is read from claude-code-action's execution file, the
// messages of the Claude run:
//   - crashed: Claude never took a turn. No file, or no assistant message
//     in it: the step died setting up (claude-code-action has already
//     retried its own install by then) or the model wasn't reachable.
//     Nothing was tried, and no completion is left to wake a later run, so
//     the action tries once more in the same job, straight away and from
//     the head as it was: one immediate retry for a third party's transient
//     error, with no pause (no fixed-time waits, ci#58). A second crash
//     releases the marker (rewrites it to a `-crashed` form the counts in
//     action.yml don't match) and says so on the PR, so a re-run of the job
//     starts afresh.
//   - failed: Claude took turns and then stopped short, whatever stopped it
//     (out of turns, an API error, the process dying). That was the
//     attempt: no retry, which would spend a second run on work the first
//     may have half done, but a comment, so the PR doesn't sit red with no
//     word.
// A fixer that pushed before failing gets neither: its push starts new runs
// on the new head, and they wake autofix.
//
// CLI, run from the app's checkout with GH_TOKEN, GITHUB_REPOSITORY, PR and
// HEAD_SHA set, and EXECUTION_FILE (the step's `execution_file` output;
// empty: RUNNER_TEMP's default file):
//   node crash.mjs retry      step outputs `retry` (crashed: resets the
//                             checkout to HEAD_SHA for it) and `report`
//                             (ran and failed)
//   node crash.mjs report ci|review   after the last try failed (RUN_URL):
//                             releases the marker or comments, as above, and
//                             exits 1 so the job shows the failure

import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { setOutput } from '../lib/actions.mjs';

/** @typedef {'ci' | 'review'} Fixer */

const BOT = 'github-actions[bot]';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n';

/**
 * Whether a Claude run never took a turn, from its execution file's text
 * (null: no file). The file is a JSON array of the run's messages; one from
 * the assistant means Claude was at work, whatever came after.
 *
 * @param {string | null} text
 * @returns {boolean}
 */
export function crashed(text) {
  if (!text) return true;
  /** @type {unknown} */
  let messages;
  try {
    messages = JSON.parse(text);
  } catch {
    return true;
  }
  if (!Array.isArray(messages)) return true;
  return !messages.some((m) => typeof m === 'object' && m !== null && m.type === 'assistant');
}

/**
 * The marker a fixer's comment carries for a head.
 *
 * @param {Fixer} fixer
 * @param {string} sha
 * @returns {string}
 */
export function markerFor(fixer, sha) {
  return fixer === 'ci' ? `<!-- autofix-ci:${sha} -->` : `<!-- autofix-review-head:${sha} -->`;
}

/**
 * The marker comment's body with its marker released, so the counts in
 * action.yml no longer see it (the review fixer's round marker goes too),
 * and a line saying why.
 *
 * @param {string} body
 * @param {Fixer} fixer
 * @param {string} sha
 * @param {string} runUrl
 * @returns {string}
 */
export function releasedBody(body, fixer, sha, runUrl) {
  const text = body
    .replaceAll(markerFor(fixer, sha), `<!-- autofix-${fixer}-crashed:${sha} -->`)
    .replace(/<!-- autofix-review-round -->\r?\n?/, '')
    .replace(FOOTER.trim(), '')
    .trimEnd();
  return `${text}\n\nClaude never got to work, twice ([run](${runUrl})), so this attempt doesn't count. Re-running that job tries again.${FOOTER}`;
}

/**
 * The comment for a fixer that ran and failed without pushing.
 *
 * @param {Fixer} fixer
 * @param {string} sha
 * @param {string} runUrl
 * @returns {string}
 */
export function failedBody(fixer, sha, runUrl) {
  const what = fixer === 'ci' ? 'the failed checks' : 'the review threads';
  return `Autofix's attempt at ${what} on ${sha.slice(0, 7)} stopped before it pushed a fix ([run](${runUrl})). It needs a person.${FOOTER}`;
}

/**
 * @param {string} name
 * @param {Record<string, string | undefined>} env
 * @returns {string}
 */
function required(name, env) {
  const value = env[name];
  if (!value) throw new Error(`${name} is not set`);
  return value;
}

/**
 * The GitHub, git and file calls the CLI makes.
 *
 * @typedef {object} Io
 * @property {(repo: string, pr: string) => string} head the PR's head SHA
 * @property {(file: string) => string | null} read null: no such file
 * @property {(file: string) => void} remove
 * @property {(sha: string) => void} reset the checkout to `sha`, clean
 * @property {(repo: string, pr: string) => { id: number, user: string, body: string }[]} comments
 * @property {(repo: string, id: number, body: string) => void} edit
 * @property {(repo: string, pr: string, body: string) => void} post
 * @property {(name: string, value: string) => void} output
 */

/**
 * The CLI, minus process handling. Returns what to print, and whether the
 * step should fail.
 *
 * @param {string[]} args
 * @param {Record<string, string | undefined>} env
 * @param {Io} io
 * @returns {{ log: string, fail: boolean }}
 */
export function main(args, env, io) {
  const [mode, fixer] = args;
  const report = mode === 'report' && (fixer === 'ci' || fixer === 'review');
  if (mode !== 'retry' && !report) {
    throw new Error('usage: crash.mjs retry | crash.mjs report ci|review');
  }
  const repo = required('GITHUB_REPOSITORY', env);
  const pr = required('PR', env);
  const sha = required('HEAD_SHA', env);
  const file =
    env.EXECUTION_FILE || path.join(required('RUNNER_TEMP', env), 'claude-execution-output.json');
  const current = io.head(repo, pr);
  if (current !== sha) {
    if (mode === 'retry') {
      io.output('retry', 'false');
      io.output('report', 'false');
    }
    return {
      log: `The fixer pushed ${current} before failing; the runs on it carry on`,
      fail: false,
    };
  }
  const didCrash = crashed(io.read(file));
  if (mode === 'retry') {
    io.output('retry', String(didCrash));
    io.output('report', String(!didCrash));
    if (!didCrash) return { log: 'Claude ran and failed: that was the attempt', fail: false };
    // From the head as it was: not what the first try left, nor its file.
    io.reset(sha);
    io.remove(file);
    return { log: 'Claude never got to work: trying once more', fail: false };
  }
  const runUrl = required('RUN_URL', env);
  const kind = /** @type {Fixer} */ (fixer);
  if (!didCrash) {
    io.post(repo, pr, failedBody(kind, sha, runUrl));
    return { log: 'Claude ran and failed: commented', fail: true };
  }
  // Only this workflow's own comment: anyone can post a look-alike.
  const marker = markerFor(kind, sha);
  const mine = io.comments(repo, pr).find((c) => c.user === BOT && c.body.includes(marker));
  if (!mine) throw new Error(`no marker comment for ${sha} on #${pr}`);
  io.edit(repo, mine.id, releasedBody(mine.body, kind, sha, runUrl));
  return { log: 'Claude never got to work, twice: released the marker', fail: true };
}

/* c8 ignore start: the CLI's lines, run by action.yml */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  /** @type {(cmd: string, args: string[], input?: string) => string} */
  const run = (cmd, args, input) =>
    execFileSync(cmd, args, { encoding: 'utf8', input, maxBuffer: 64 * 1024 * 1024 });
  /** @type {Io} */
  const io = {
    head: (repo, pr) => run('gh', ['api', `repos/${repo}/pulls/${pr}`, '--jq', '.head.sha']).trim(),
    read: (file) => {
      try {
        return readFileSync(file, 'utf8');
      } catch {
        return null;
      }
    },
    remove: (file) => rmSync(file, { force: true }),
    reset: (sha) => {
      run('git', ['reset', '--hard', sha]);
      run('git', ['clean', '-ffd']);
    },
    comments: (repo, pr) =>
      /** @type {{ id: number, user: { login: string }, body: string }[][]} */ (
        JSON.parse(
          run('gh', ['api', '--paginate', '--slurp', `repos/${repo}/issues/${pr}/comments`]),
        )
      )
        .flat()
        .map((c) => ({ id: c.id, user: c.user.login, body: c.body })),
    edit: (repo, id, body) => {
      run(
        'gh',
        ['api', '-X', 'PATCH', `repos/${repo}/issues/comments/${id}`, '-F', 'body=@-'],
        body,
      );
    },
    post: (repo, pr, body) => {
      run('gh', ['pr', 'comment', pr, '--repo', repo, '--body-file', '-'], body);
    },
    output: setOutput,
  };
  const { log, fail } = main(process.argv.slice(2), process.env, io);
  console.log(log);
  if (fail) process.exitCode = 1;
}
